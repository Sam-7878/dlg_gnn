"""Build the R324 TDS article candidates (Preprints.org and Applied Sciences) and the Supplement.

Usage (from anywhere):
    python scripts/revision324/build.py            # review build (DOI placeholder allowed)
    python scripts/revision324/build.py --final    # refuses while the DOI placeholder remains

Sources: paper/submission_324/common (shared, byte-identical in both venues)
         paper/submission_324/venues/{preprints,applsci} (template wrappers only)
Outputs: submission/{preprints,applsci}/324/  (PDFs, source ZIP, metadata.json)
         reports/324/build_receipt.json and *_build.log
"""
import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import tempfile
from pathlib import Path
from zipfile import ZIP_DEFLATED, ZipFile

PROJECT = Path(__file__).resolve().parents[2]
PAPER = PROJECT / 'paper/submission_324'
COMMON = PAPER / 'common'
REPORTS = PROJECT / 'reports/324'
PLACEHOLDER = 'DOI-PLACEHOLDER'
VENUES = {
    'preprints': ('preprint_main', 'preprint_source.zip', 'preprint_article.pdf'),
    'applsci': ('applsci_article', 'mdpi_source.zip', 'applsci_article.pdf'),
}
# Reproducible PDFs: fixed creation date (the R324 build date) and no PDF ID randomness.
ENV = {**os.environ, 'SOURCE_DATE_EPOCH': '1795651200', 'FORCE_SOURCE_DATE': '1'}
BAD_LOG = re.compile(r'Overfull \\hbox|undefined|Undefined supplement reference|Citation .* undefined|Reference .* undefined')


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def latexmk(cwd, stem, log_name):
    REPORTS.mkdir(parents=True, exist_ok=True)
    with (REPORTS / log_name).open('w') as log:
        subprocess.run(['latexmk', '-pdf', '-interaction=nonstopmode', '-halt-on-error', stem + '.tex'],
                       cwd=cwd, stdout=log, stderr=subprocess.STDOUT, check=True, env=ENV)
    text = (cwd / (stem + '.log')).read_text(errors='replace')
    bad = [line for line in text.splitlines() if BAD_LOG.search(line)]
    assert not bad, f'{stem}: ' + '\n'.join(bad[:10])
    return [line for line in text.splitlines() if 'Warning' in line]


def supplement_refs(aux_text):
    """Map Supplement labels to their table numbers for use as \\STab{label} in the article."""
    lines = [r'% Generated by scripts/revision324/build.py from the Supplement .aux file. Do not edit.',
             r'\newcommand{\STab}[1]{\ifcsname tdsS@#1\endcsname Table~\csname tdsS@#1\endcsname'
             r'\else\textbf{Table~S??}\PackageWarning{tds}{Undefined supplement reference #1}\fi}']
    labels = {}
    for label, number in re.findall(r'\\newlabel\{(tab:[^}]+)\}\{\{(S\d+)\}', aux_text):
        labels[label] = number
        lines.append(r'\expandafter\def\csname tdsS@' + label + r'\endcsname{' + number + '}')
    return '\n'.join(lines) + '\n', labels


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--final', action='store_true')
    args = parser.parse_args()
    sources = [p for p in COMMON.rglob('*.tex')]
    if args.final:
        hits = [str(p) for p in sources if PLACEHOLDER in p.read_text()]
        assert not hits, f'--final refused: DOI placeholder remains in {hits}'

    # 1. Supplement first, to number its tables.
    with tempfile.TemporaryDirectory(prefix='tds324-supp-') as folder:
        tmp = Path(folder) / 'tree'
        shutil.copytree(COMMON, tmp, ignore=shutil.ignore_patterns('*.aux', '*.log', '*.pdf.tmp'))
        (tmp / 'supplement_refs.tex').write_text('')
        latexmk(tmp / 'supplement', 'supplement', 'supplement_numbering_build.log')
        refs, labels = supplement_refs((tmp / 'supplement/supplement.aux').read_text())
    (COMMON / 'supplement_refs.tex').write_text(refs)

    receipt = {'final': args.final, 'supplement_labels': labels, 'venues': {}}
    for venue, (entry, zipname, pdfname) in VENUES.items():
        stage = PAPER / 'build' / venue
        if stage.exists():
            shutil.rmtree(stage)
        shutil.copytree(COMMON, stage, ignore=shutil.ignore_patterns('abstract.txt', 'keywords.txt', '*.py', '*.svg'))
        for item in (PAPER / 'venues' / venue).iterdir():
            target = stage / item.name
            shutil.copytree(item, target) if item.is_dir() else shutil.copyfile(item, target)
        out = PROJECT / 'submission' / venue / '324'
        out.mkdir(parents=True, exist_ok=True)
        with ZipFile(out / zipname, 'w', ZIP_DEFLATED) as z:
            for f in sorted(stage.rglob('*')):
                if f.is_file():
                    z.write(f, f.relative_to(stage))
        notices = latexmk(stage, entry, f'{venue}_{entry}_build.log')
        notices += latexmk(stage / 'supplement', 'supplement', f'{venue}_supplement_build.log')
        shutil.copyfile(stage / (entry + '.pdf'), out / pdfname)
        shutil.copyfile(stage / 'supplement/supplement.pdf', out / 'supplement.pdf')
        files = {f.name: sha(f) for f in sorted(out.iterdir()) if f.suffix in ('.pdf', '.zip')}
        (out / 'metadata.json').write_text(json.dumps({
            'candidate_id': 'TDS_R324_REVIEW_CANDIDATE', 'final_build': args.final,
            'data_doi': None, 'preprint_doi': None, 'submission_status': 'NOT_SUBMITTED',
            'files': {n: {'path': f'projects/tds/submission/{venue}/324/{n}', 'sha256': h} for n, h in files.items()},
        }, indent=2) + '\n')
        receipt['venues'][venue] = {'notices': notices, 'files': files}

    a, b = PAPER / 'build/preprints', PAPER / 'build/applsci'
    shared = [p.relative_to(COMMON) for p in COMMON.rglob('*')
              if p.is_file() and p.suffix in ('.tex', '.bib', '.pdf')]
    for rel in shared:
        assert (a / rel).read_bytes() == (b / rel).read_bytes(), rel
    receipt['shared_files_identical'] = len(shared)
    (REPORTS / 'build_receipt.json').write_text(json.dumps(receipt, indent=2) + '\n')
    print('R324 build PASS', json.dumps({v: r['files'] for v, r in receipt['venues'].items()}, indent=1))


if __name__ == '__main__':
    main()
